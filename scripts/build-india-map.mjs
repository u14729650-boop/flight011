/**
 * Builds src/data/indiaMap.generated.ts from DataMeet's India state boundaries
 * (https://github.com/datameet/maps, States/Admin2 — follows the official
 * Survey of India outline). Licensed CC BY 2.5 India — keep the attribution
 * shown in the map components.
 *
 * Run: npm run map:build   (downloads the source shapefile on first run)
 */
import fs from 'node:fs';
import path from 'node:path';
import * as shapefile from 'shapefile';
import { geoMercator, geoPath, geoCentroid } from 'd3-geo';
import { topology } from 'topojson-server';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { feature, mesh } from 'topojson-client';

const SRC = 'https://raw.githubusercontent.com/datameet/maps/master/States/Admin2';
const cacheDir = path.resolve('node_modules/.cache/india-map');
const out = path.resolve('src/data/indiaMap.generated.ts');
const WIDTH = 1000;
const HEIGHT = 1120;

fs.mkdirSync(cacheDir, { recursive: true });
for (const ext of ['shp', 'dbf']) {
  const file = path.join(cacheDir, `Admin2.${ext}`);
  if (!fs.existsSync(file)) {
    console.log(`Downloading Admin2.${ext}…`);
    const res = await fetch(`${SRC}.${ext}`);
    if (!res.ok) throw new Error(`Download failed: ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
}

const geo = await shapefile.read(path.join(cacheDir, 'Admin2.shp'), path.join(cacheDir, 'Admin2.dbf'));
const NAME_FIX = {
  'Andaman & Nicobar': 'Andaman and Nicobar Islands',
  'Jammu & Kashmir': 'Jammu and Kashmir',
};
for (const f of geo.features) {
  const n = f.properties.ST_NM.trim();
  f.properties = { name: NAME_FIX[n] ?? n };
}

let topo = topology({ states: geo }, 1e5);
topo = presimplify(topo);
topo = simplify(topo, quantile(topo, 0.009));
const simplified = feature(topo, topo.objects.states);

const projection = geoMercator().fitExtent([[12, 12], [WIDTH - 12, HEIGHT - 12]], simplified);
const pathGen = geoPath(projection).digits(1);

const states = simplified.features
  .map((f) => {
    const [cx, cy] = projection(geoCentroid(f));
    return { name: f.properties.name, d: pathGen(f), cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const outline = pathGen(mesh(topo, topo.objects.states, (a, b) => a === b));
const [tx, ty] = projection.translate();

const ts = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-india-map.mjs — do not edit by hand.
// Source: DataMeet India Maps (States/Admin2), CC BY 2.5 India.

export const INDIA_MAP_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;

/** Mercator projection parameters used to draw the paths below. */
export const INDIA_MAP_PROJECTION = { scale: ${projection.scale()}, tx: ${tx}, ty: ${ty} } as const;

export interface IndiaStateShape { name: string; d: string; cx: number; cy: number }

export const INDIA_STATE_SHAPES: IndiaStateShape[] = ${JSON.stringify(states)};

export const INDIA_OUTLINE_PATH = ${JSON.stringify(outline)};
`;
fs.writeFileSync(out, ts);
console.log(`Wrote ${out} (${(ts.length / 1024).toFixed(0)} KB, ${states.length} states/UTs)`);
